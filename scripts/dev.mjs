// Static dev server for Eye Catcher: npm run dev -> http://localhost:5177/
// Serves this folder, makes env.js from .env, and reloads open pages when a file changes. No dependencies. The desktop
// app (desktop/main.mjs) runs the same server inside itself, with a route that streams the player's recordings.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
export const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.mjs': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webm': 'video/webm', '.mp4': 'video/mp4', '.m4v': 'video/mp4', '.mov': 'video/quicktime', '.mkv': 'video/x-matroska' };
const RELOAD = '<script src="/__reload.js"></script>';

export function readEnv(file) {
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch { return {}; }
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const m = /^(?:export\s+)?([A-Za-z_]\w*)\s*=\s*(.*)$/.exec(raw.trim());
    if (!m || raw.trim().startsWith('#')) continue;
    out[m[1]] = /^(['"]).*\1$/.test(m[2].trim()) ? m[2].trim().slice(1, -1) : m[2].replace(/\s+#.*$/, '').trim();
  }
  return out;
}

// a DNS-rebinding page also connects from 127.0.0.1, but under its own Host name
const localName = (h) => /^(localhost|127\.0\.0\.1|\[::1\])(:\d+)?$/i.test(h || '');
const localPeer = (req) => ['127.0.0.1', '::1', '::ffff:127.0.0.1'].includes(req.socket.remoteAddress) && localName(req.headers.host);

// THIRDEYE_COACH_MODEL can come from the launch too, to try the coach on another model without touching .env, and so
// can THIRDEYE_FLAGS, the experiments a review runs with (agent.js flag)
const envOf = (overrides) => ({ ...readEnv(path.join(root, '.env')), ...Object.fromEntries(['THIRDEYE_COACH_MODEL', 'THIRDEYE_FLAGS'].filter((k) => process.env[k]).map((k) => [k, process.env[k]])), ...overrides });

// Any page open in the browser can load this server's files as scripts, on this machine too, so the key goes only to
// Eye Catcher's own page: the browser marks that request same-origin (Sec-Fetch-Site), and a page can't fake the mark.
const ownPage = (req) => localPeer(req) && req.headers['sec-fetch-site'] === 'same-origin';

function envScript(req, overrides = {}) {
  const env = envOf(overrides);
  const pub = {};
  if (env.GEMINI_MODEL) pub.GEMINI_MODEL = env.GEMINI_MODEL;
  if (env.THIRDEYE_COACH_MODEL) pub.COACH_MODEL = env.THIRDEYE_COACH_MODEL; // the coach's turns only, tried first
  // comma-separated names, like near_loss,state_facts; anything else is left out
  if (env.THIRDEYE_FLAGS) pub.FLAGS = String(env.THIRDEYE_FLAGS).split(',').map((x) => x.trim()).filter((x) => /^[a-z0-9_]{1,40}$/.test(x)).join(',');
  // with Eye Catcher's backend the key stays there
  if (env.THIRDEYE_BACKEND) pub.THIRDEYE_BACKEND = env.THIRDEYE_BACKEND;
  else if (env.GEMINI_API_KEY && ownPage(req)) {
    pub.GEMINI_API_KEY = env.GEMINI_API_KEY;
    // a second key, for when the first is out of its daily limit (gemini.js)
    if (env.GEMINI_API_KEY2) pub.GEMINI_API_KEY2 = env.GEMINI_API_KEY2;
    // THIRDEYE_SECOND_KEY_FIRST=1 at launch: start on the second key, the first as its spare
    if (process.env.THIRDEYE_SECOND_KEY_FIRST === '1' && env.GEMINI_API_KEY2) [pub.GEMINI_API_KEY, pub.GEMINI_API_KEY2] = [env.GEMINI_API_KEY2, env.GEMINI_API_KEY];
  }
  return `/* Generated by scripts/dev.mjs from .env. Do not commit. */\nwindow.__ENV__ = Object.freeze(${JSON.stringify(pub)});\n`;
}

// What the page may load and talk to. Its code is all its own (vendor/ holds the libraries), so a script that got into
// it couldn't load more or send anything anywhere but Eye Catcher's own server and Gemini (or the backend). Styles may be
// inline: the page positions marks with style attributes. Stockfish's worker gets no policy of its own and needs none:
// it can't reach the page.
export function policy(env) {
  const gemini = env.THIRDEYE_BACKEND ? new URL(env.THIRDEYE_BACKEND).origin : 'https://generativelanguage.googleapis.com';
  return [
    "default-src 'self'", "script-src 'self'", "worker-src 'self'",
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com", 'font-src https://fonts.gstatic.com',
    "img-src 'self' data: blob:", "media-src 'self' blob:", `connect-src 'self' ${gemini}`,
    "object-src 'none'", "base-uri 'none'", "frame-src 'none'", "frame-ancestors 'none'", "form-action 'self'",
  ].join('; ');
}

// Range requests let <video> seek inside a large file without loading all of it.
function sendFile(req, res, p, type) {
  const size = fs.statSync(p).size, range = /^bytes=(\d*)-(\d*)$/.exec(req.headers.range || '');
  if (!range) { res.writeHead(200, { 'Content-Type': type, 'Content-Length': size, 'Accept-Ranges': 'bytes', 'Cache-Control': 'no-store' }); return fs.createReadStream(p).pipe(res); }
  const start = range[1] ? +range[1] : size - +range[2], end = range[1] && range[2] ? Math.min(+range[2], size - 1) : size - 1;
  if (!(start >= 0 && start <= end)) { res.writeHead(416, { 'Content-Range': `bytes */${size}` }); return res.end(); }
  res.writeHead(206, { 'Content-Type': type, 'Content-Length': end - start + 1, 'Content-Range': `bytes ${start}-${end}/${size}`, 'Accept-Ranges': 'bytes', 'Cache-Control': 'no-store' });
  fs.createReadStream(p, { start, end }).pipe(res);
}

// GET: which voices there are (404 without Kokoro). POST { text, voice }: the line as WAV.
async function voiceRoute(req, res) {
  const voice = await import('./voice.mjs');
  if (!voice.available()) { res.writeHead(404); return res.end(); }
  if (req.method === 'GET') { res.writeHead(200, { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' }); return res.end(JSON.stringify({ voices: voice.VOICES })); }
  if (req.method !== 'POST') { res.writeHead(405); return res.end(); }
  let body = '';
  for await (const chunk of req) { body += chunk; if (body.length > 4000) { res.writeHead(413); return res.end(); } }
  try {
    const { text, voice: name } = JSON.parse(body || '{}');
    const wav = await voice.speech({ text, voice: name });
    res.writeHead(200, { 'Content-Type': 'audio/wav', 'Cache-Control': 'no-store', 'Content-Length': wav.length });
    res.end(wav);
  } catch (e) {
    res.writeHead(400, { 'Content-Type': 'application/json' });
    res.end(JSON.stringify({ error: String(e?.message || e).slice(0, 200) }));
  }
}

/**
 * Starts the server. reload: reload open pages when a file changes. recording(token): the path of a recording the
 * desktop app streams at /recording/<token>, or null. env: values that win over .env in env.js. Resolves with
 * { port, close }.
 */
export function startServer({ port = 5177, host = '127.0.0.1', reload = true, recording = null, env = {} } = {}) {
  const clients = new Set();
  const server = http.createServer((req, res) => {
    let url;
    try { url = decodeURIComponent(req.url.split('?')[0]); } catch { res.writeHead(400); return res.end(); }
    // nothing here can be embedded or read by a page from anywhere else
    res.setHeader('Cross-Origin-Resource-Policy', 'same-origin');
    res.setHeader('X-Content-Type-Options', 'nosniff');
    res.setHeader('Referrer-Policy', 'no-referrer');
    if (url === '/__reload.js' && reload) { res.writeHead(200, { 'Content-Type': 'text/javascript', 'Cache-Control': 'no-store' }); return res.end("new EventSource('/__reload').onmessage = () => location.reload();\n"); }
    if (url === '/__reload') {
      res.writeHead(200, { 'Content-Type': 'text/event-stream', 'Cache-Control': 'no-cache', Connection: 'keep-alive' });
      res.write(': connected\n\n'); clients.add(res); req.on('close', () => clients.delete(res));
      return;
    }
    if (url === '/env.js') { res.writeHead(200, { 'Content-Type': 'text/javascript', 'Cache-Control': 'no-store' }); return res.end(envScript(req, env)); }
    // the critique's voice, made on this machine (voice.mjs): for Eye Catcher's own page only, like the key
    if (url === '/voice') {
      if (!ownPage(req)) { res.writeHead(403); return res.end(); }
      return voiceRoute(req, res);
    }
    if (url.startsWith('/recording/')) {
      const p = recording && localPeer(req) ? recording(url.slice('/recording/'.length)) : null;
      if (!p || !fs.existsSync(p)) { res.writeHead(404); return res.end(); }
      return sendFile(req, res, p, TYPES[path.extname(p).toLowerCase()] || 'application/octet-stream');
    }
    if (url.split('/').some((seg) => seg.startsWith('.') || seg === 'node_modules')) { res.writeHead(404); return res.end(); }
    let p = path.join(root, url);
    if (!p.startsWith(root + path.sep) && p !== root) { res.writeHead(403); return res.end(); }
    if (fs.existsSync(p) && fs.statSync(p).isDirectory()) p = path.join(p, 'index.html');
    if (!fs.existsSync(p)) { res.writeHead(404); return res.end('Not found'); }
    const type = TYPES[path.extname(p)] || 'application/octet-stream';
    if (path.extname(p) !== '.html') return sendFile(req, res, p, type);
    res.writeHead(200, { 'Content-Type': type, 'Cache-Control': 'no-store', 'Content-Security-Policy': policy(envOf(env)) });
    const html = fs.readFileSync(p, 'utf8');
    res.end(reload ? html.replace('</body>', `${RELOAD}</body>`) : html);
  });

  let watcher = null;
  if (reload) {
    let timer;
    watcher = fs.watch(root, { recursive: true }, (_, file) => {
      // eval logs and test fixtures change while reviews run; reloading for them would cut a review off
      if (!file || /(^|\/)(\.|node_modules|tests\/out|tests\/fixtures|eval\/)/.test(file)) return;
      clearTimeout(timer);
      timer = setTimeout(() => clients.forEach((c) => c.write('data: reload\n\n')), 120);
    });
  }
  return new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, host, () => resolve({
      port: server.address().port,
      close: () => { watcher?.close(); clients.forEach((c) => c.end()); server.close(); },
    }));
  });
}

if (fileURLToPath(import.meta.url) === path.resolve(process.argv[1] || '')) {
  const { port } = await startServer({ port: +(process.env.PORT || 5177), host: process.env.HOST || '127.0.0.1' });
  console.log(`Eye Catcher: http://localhost:${port}/`);
}
